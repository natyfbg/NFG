"""The Muscle Mixer's tappable body: art regions mapped onto the taxonomy.

The figures come from bodymap_paths.py (generated by scripts/import_bodymap.py). Each art
region is mapped to taxonomy *muscle* keys; the group then comes from
taxonomy.groups_for_muscles (which honours MUSCLE_HOME_GROUP, so rear delts light up
Shoulders). Change group membership in taxonomy.py and the body follows.

No Flask or Mongo imports, on purpose (like taxonomy.py).
"""

from __future__ import annotations

from typing import Dict, List, Optional, Tuple

import bodymap_paths as art
import taxonomy as tx

VIEWS = ("front", "back")

# (view, art slug) -> taxonomy muscle keys. Anything not listed is decorative.
REGION_MUSCLES: Dict[Tuple[str, str], List[str]] = {
    ("front", "chest"): ["chest", "upper_chest"],
    ("front", "deltoids"): ["front_delts", "side_delts"],
    ("back", "deltoids"): ["rear_delts"],
    ("front", "trapezius"): ["traps"],
    ("back", "trapezius"): ["traps"],
    ("back", "upper-back"): ["lats", "upper_back"],
    ("back", "lower-back"): ["lower_back"],
    ("front", "biceps"): ["biceps"],
    ("front", "triceps"): ["triceps"],
    ("back", "triceps"): ["triceps"],
    ("front", "forearm"): ["forearms"],
    ("back", "forearm"): ["forearms"],
    ("front", "abs"): ["abs"],
    ("front", "obliques"): ["obliques"],
    ("front", "quadriceps"): ["quads"],
    ("front", "adductors"): ["adductors"],
    ("back", "adductors"): ["adductors"],
    ("back", "gluteal"): ["glutes"],
    ("back", "hamstring"): ["hamstrings"],
    ("front", "calves"): ["calves"],
    ("back", "calves"): ["calves"],
    ("front", "tibialis"): ["calves"],
}
DECORATIVE = {"head", "hair", "neck", "hands", "feet", "ankles", "knees"}

# Workout types sit beside the body rather than on it.
NON_BODY_GROUPS = ("full_body", "cardio", "mobility")

_ART = {"front": art.FRONT, "back": art.BACK}
_VIEWBOX = {"front": art.VIEWBOX_FRONT, "back": art.VIEWBOX_BACK}
_OUTLINE = {"front": art.OUTLINE_FRONT, "back": art.OUTLINE_BACK}


def region_group(view: str, slug: str) -> Optional[str]:
    """The muscle group an art region belongs to, or None for decorative parts."""
    muscles = REGION_MUSCLES.get((view, slug))
    if not muscles:
        return None
    groups = tx.groups_for_muscles(muscles)
    return groups[0] if groups else None


def body_regions(view: str) -> List[dict]:
    """What the template draws, in art order: [{slug, paths, group}] (group None = decor)."""
    return [
        {"slug": r["slug"], "paths": r["paths"], "group": region_group(view, r["slug"])}
        for r in _ART[view]
    ]


def figure(view: str) -> dict:
    return {
        "view": view,
        "viewbox": _VIEWBOX[view],
        "outline": _OUTLINE[view],
        "regions": body_regions(view),
    }


def body_groups() -> List[str]:
    """Muscle groups that can be picked on the body, in taxonomy order."""
    return [k for k in tx.MUSCLE_GROUPS if k not in NON_BODY_GROUPS]


# -----------------------------------------------------------------------------
# Colour: white text on a group colour must be readable (WCAG AA, 4.5:1)
# -----------------------------------------------------------------------------
def _luminance(hex_color: str) -> float:
    h = hex_color.lstrip("#")
    channels = [int(h[i : i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast_with_white(hex_color: str) -> float:
    return 1.05 / (_luminance(hex_color) + 0.05)


def readable_on_white(hex_color: str, ratio: float = 4.5) -> str:
    """The colour, darkened just enough for white text on it to reach `ratio`."""
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) for i in (0, 2, 4))
    out = f"#{r:02X}{g:02X}{b:02X}"
    factor = 1.0
    while contrast_with_white(out) < ratio and factor > 0.05:
        factor -= 0.02
        out = "#{:02X}{:02X}{:02X}".format(*(int(c * factor) for c in (r, g, b)))
    return out
